'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const { spawnSync } = require('node:child_process');
const { CodexBridge } = require('./codex-bridge');
const plot = require('./plotting');
const parent = path.resolve(__dirname,'../.workbench');
const directory = fs.mkdtempSync(path.join(parent,'plotting-test-'));
const bridge = new CodexBridge(directory);
const python = path.resolve(__dirname,'../.venv',process.platform==='win32'?'Scripts/python.exe':'bin/python');
const runtime = plot.prepareRuntime;
const rpcCalls=[];
let prepared=0;
plot.prepareRuntime=async()=>{prepared++;return python;};
bridge.status=async()=>({loggedIn:true,model:'test-model',models:[{model:'test-model',defaultReasoningEffort:'low'}]});
bridge.rpc=async(method,params)=>{ rpcCalls.push({method,params}); return method==='thread/start' ? {thread:{id:randomUUID()}} : {turn:{id:randomUUID()}}; };
const waitTurn=async(id)=>{for(let n=0;n<100&&!bridge.jobs.get(id).turnId;n++)await new Promise(r=>setTimeout(r,5));assert(bridge.jobs.get(id).turnId);};
async function main(){
  const session=bridge.createSession().id;
  const uploaded=bridge.upload(session,'demo.csv',Buffer.from('year,value\n2020,1\n2021,2\n2022,4\n'));
  const plan={text:'折线图，year为横轴，value为纵轴；不聚合、不改原始值，PNG/SVG/PDF和代码。',version:1,inputNames:[uploaded.name]};
  const messages=[{role:'user',content:'按已审核方案生成'}];
  await assert.rejects(bridge.run(session,messages,'',true,null,'plotting',null),/审核/);
  await assert.rejects(bridge.run(session,messages,'',true,null,'plotting',null,{...plan,inputNames:['../secret.csv']}));
  await assert.rejects(bridge.run(session,messages,'',true,null,'plotting',null,{...plan,previousRunId:randomUUID()}));
  assert.equal(bridge.jobs.size,0);
  const discussion=await bridge.run(session,messages,'',false,null,'plotting',null);
  await waitTurn(discussion.id);
  assert.equal(prepared,1,'prepare data readers without allowing writes during discussion');
  assert.equal(rpcCalls.at(-1).params.sandboxPolicy.type,'readOnly');
  bridge.finish(bridge.jobs.get(discussion.id),'completed');
  assert.equal(plot.runs(bridge,session).length,0);

  const run=await bridge.run(session,messages,'绘图',true,'test-model','plotting',null,plan);
  await waitTurn(run.id);
  const work=path.join(bridge.session(session),'output',run.id);
  const frozen=JSON.parse(fs.readFileSync(path.join(work,plot.PLAN),'utf8'));
  assert.equal(frozen.version,1); assert.equal(frozen.inputFiles[0].sha256.length,64);
  const turn=rpcCalls.at(-1).params;
  assert.deepEqual(turn.sandboxPolicy.writableRoots,[work]); assert.equal(turn.sandboxPolicy.networkAccess,false);
  assert.equal(turn.sandboxPolicy.type,'workspaceWrite');
  assert.match(rpcCalls.at(-2).params.developerInstructions,/plot-data.csv/);
  fs.writeFileSync(path.join(work,'plot-data.csv'),'year,value\n2020,1\n2021,2\n2022,4\n');
  fs.writeFileSync(path.join(work,'plot.py'),"from pathlib import Path\nimport pandas as pd\nimport matplotlib\nmatplotlib.use('Agg')\nimport matplotlib.pyplot as plt\np=Path(__file__).parent\nd=pd.read_csv(p/'plot-data.csv')\nplt.plot(d.year,d.value)\nplt.xlabel('Year')\nplt.ylabel('Value')\nfor ext in ['png','svg','pdf']: plt.savefig(p/('figure.'+ext))\n");
  const rendered=spawnSync(python,[path.join(work,'plot.py')],{encoding:'utf8',windowsHide:true,timeout:30000});
  assert.equal(rendered.status,0,rendered.stderr);
  bridge.finish(bridge.jobs.get(run.id),'completed');
  assert.equal(bridge.snapshot(run.id).status,'completed');
  assert.equal(plot.rasterType(path.join(work,'figure.png')),'image/png');
  assert.throws(()=>plot.rasterType(path.join(work,'figure.svg')),/不是可预览/);
  fs.writeFileSync(path.join(work,'fake.png'),'<html>not an image</html>');
  assert.throws(()=>plot.rasterType(path.join(work,'fake.png')),/不是可预览/);
  fs.unlinkSync(path.join(work,'fake.png'));
  const record=plot.runs(bridge,session)[0];
  assert.equal(record.model,'test-model');assert.equal(record.status,'completed');
  assert(record.files.some(file=>file.name.endsWith('/plot.py')));
  assert(record.files.some(file=>file.name.endsWith('/figure.pdf')));
  const originalImage=fs.readFileSync(path.join(work,'figure.png'));
  const second=await bridge.run(session,messages,'',true,null,'plotting',null,{...plan,version:2,previousRunId:run.id});
  await waitTurn(second.id);
  bridge.finish(bridge.jobs.get(second.id),'completed');
  assert.equal(bridge.snapshot(second.id).status,'failed','text-only success cannot pass as a figure');
  assert(fs.readFileSync(path.join(work,'figure.png')).equals(originalImage));
  const recovered=new CodexBridge(directory);
  const history=plot.runs(recovered,session);
  assert.equal(history.length,2);assert.equal(history[0].previousRunId,run.id);
  assert.equal(history[1].status,'completed');
  const interrupted=await bridge.run(session,messages,'',true,null,'plotting',null,plan);
  await waitTurn(interrupted.id);
  assert.equal(plot.runs(recovered,session)[0].status,'interrupted');
  bridge.finish(bridge.jobs.get(interrupted.id),'cancelled');
  assert.equal(plot.runs(recovered,session)[0].status,'cancelled');
  console.log('PLOTTING_TESTS_PASS: approval, file scope, runtime, real PNG/SVG/PDF, code, versions, failure and restart');
}
main().catch(error=>{console.error(error);process.exitCode=1;}).finally(()=>{
  plot.prepareRuntime=runtime;
  for(const job of bridge.jobs.values())clearTimeout(job.timer);
  const target=path.resolve(directory);assert(target.startsWith(parent+path.sep));
  fs.rmSync(target,{recursive:true,force:true});
});
