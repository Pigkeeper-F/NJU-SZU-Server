'use strict';
// Actual Store in memory: no service, cleaning, browser or research task.
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm'), assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const source = fs.readFileSync(path.join(__dirname, '../js/store.js'), 'utf8');
const storage = new Map();
const browser = { localStorage: { getItem: key => storage.get(key) || null, setItem: (key, value) => storage.set(key, value) } };
vm.runInNewContext(source, { window: browser });
let store = browser.Store; const clean = store.addModule('数据清洗');
const text = '# 已确认合成清洗方案\n保留原始记录。'; store.saveDoc(clean.id, text); store.approveDoc(clean.id);
store.markRun(clean.id, { dir: 'legacy-result', artifacts: [{ name: 'old.csv', size: 1 }] });
assert.equal(store.confirmRun(clean.id), false, 'Old result confirmation cannot bypass verification');
assert.equal(store.approveModule(clean.id).ok, false);
const marker = { runId: randomUUID(), reportId: randomUUID(), planSha256: 'a'.repeat(64), planText: text };
store.markRun(clean.id, { dir: marker.runId, artifacts: [{ name: 'cleaned.csv', size: 10 }], cleanAcceptance: marker });
assert.equal(store.confirmRun(clean.id), true);
vm.runInNewContext(source, { window: browser }); store = browser.Store;
assert.equal(store.getState().modules.find(item => item.id === clean.id).run.cleanAcceptance.reportId, marker.reportId, 'Refresh retains evidence reference');
assert.equal(store.approveModule(clean.id).ok, true);
assert.equal(store.invalidateCleanAcceptance(clean.id, randomUUID(), '修改另一次历史核验'), false, 'A different historical run cannot withdraw this acceptance');
assert.equal(store.invalidateCleanAcceptance(clean.id, marker.runId, '人工核验结论已更新'), true);
const withdrawn = store.getState().modules.find(item => item.id === clean.id);
assert.equal(withdrawn.run.status, 'ran'); assert.equal(withdrawn.run.cleanAcceptance, undefined);
assert.equal(withdrawn.status, 'doing'); assert.equal(withdrawn.run.artifacts[0].name, 'cleaned.csv');
assert.equal(store.confirmRun(clean.id), false, 'Changing a manual conclusion withdraws approval while preserving files');
store.markRun(clean.id, { dir: marker.runId, artifacts: [{ name: 'cleaned.csv', size: 10 }], cleanAcceptance: marker });
assert.equal(store.confirmRun(clean.id), true);
browser.TaskManager = { rulesForModule: () => ({ text: '新版已确认规则', version: 2 }) };
assert.equal(store.approveModule(clean.id).ok, false, 'Changed rules invalidate old acceptance');
delete browser.TaskManager;
store.saveDoc(clean.id, '# 新方案草稿');
const changed = store.getState().modules.find(item => item.id === clean.id);
assert.equal(changed.run.status, 'ran'); assert.equal(changed.run.cleanAcceptance, undefined);
assert.equal(changed.run.artifacts[0].name, 'cleaned.csv', 'Keep existing outputs when rules change');
assert.equal(store.confirmRun(clean.id), false);
console.log('CLEAN_ACCEPTANCE_STORE_PASS (no direct bypass, durable references, changed-rule invalidation, preserved artifacts)');
